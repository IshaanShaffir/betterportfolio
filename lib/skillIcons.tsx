// Helper function to get icon component by name
export function getSkillIcon(skillName: string, iconOverride?: string) {
  if (iconOverride) {
    // If there's a custom icon override, try to use it
    const Icon = skillIconMap[iconOverride.toLowerCase()];
    if (Icon) return Icon;
  }

  // Try to find icon by skill name
  const Icon = skillIconMap[skillName.toLowerCase()];
  if (Icon) return Icon;

  // Default fallback icon
  return FaCode;
}
